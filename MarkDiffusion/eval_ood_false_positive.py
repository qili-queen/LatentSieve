def summarize(values):
    if not values:
        return None
    values = [float(v) for v in values]
    return {
        "count": len(values),
        "mean": float(sum(values) / len(values)),
        "std": float(torch.tensor(values, dtype=torch.float32).std(unbiased=False).item()),
        "min": float(min(values)),
        "max": float(max(values)),
    }


def to_jsonable(value):
    if isinstance(value, dict):
        return {k: to_jsonable(v) for k, v in value.items()}
    if isinstance(value, list):
        return [to_jsonable(v) for v in value]
    if isinstance(value, tuple):
        return [to_jsonable(v) for v in value]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if hasattr(value, "item"):
        try:
            return value.item()
        except Exception:
            return str(value)
    return str(value)


def reseed_watermark(watermark, seed):
    watermark.config.gen_seed = seed
    watermark.config.init_latents_seed = seed
    latents_rng = torch.Generator(device=watermark.config.device)
    latents_rng.manual_seed(seed)
    watermark.config.init_latents = get_random_latents(
        watermark.config.pipe,
        height=watermark.config.image_size[0],
        width=watermark.config.image_size[1],
        generator=latents_rng,
    ).to(watermark.config.device, dtype=watermark.config.dtype)


def download_coco_images(cache_dir, max_images=20):
    """Download COCO val images to cache directory."""
    cache_dir = Path(cache_dir)
    cache_dir.mkdir(parents=True, exist_ok=True)
    images = []
    for url in COCO_URLS[:max_images]:
        fname = url.split("/")[-1]
        fpath = cache_dir / fname
        if not fpath.exists():
            print(f"  Downloading {url}...")
            try:
                urllib.request.urlretrieve(url, str(fpath))
            except Exception as e:
                print(f"  Failed to download {url}: {e}")
                continue
        try:
            img = Image.open(fpath).convert("RGB").resize((512, 512), Image.BICUBIC)
            images.append((str(fpath), img))
        except Exception as e:
            print(f"  Failed to load {fpath}: {e}")
    return images


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="huanzi05/stable-diffusion-2-1-base")
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument("--size", type=int, default=512)
    parser.add_argument("--gpu", type=int, default=None)
    parser.add_argument("--algorithm", default="RSWST",
                        help="watermark to evaluate; the OOD control row of the paper needs MIRAGE")
    parser.add_argument("--config", default="config/RSWST_presence.json")
    parser.add_argument("--coco-cache-dir", default="qi_coco_cache")
    parser.add_argument("--max-coco", type=int, default=20)
    parser.add_argument("--max-ood-prompts", type=int, default=20)
    parser.add_argument("--num-seeds-per-prompt", type=int, default=1)
    parser.add_argument("--output", default="qi_ood_false_positive.json")
    parser.add_argument("--csv-output", default="qi_ood_false_positive.csv")
    args = parser.parse_args()

    device, dtype = resolve_qi_device(args.gpu)
    pipe, scheduler = build_cached_pipe(args.model, device, dtype)
    diffusion_config = DiffusionConfig(
        scheduler=scheduler,
        pipe=pipe,
        device=device,
        image_size=(args.size, args.size),
        num_inference_steps=args.steps,
        num_inversion_steps=args.steps,
        guidance_scale=7.5,
        gen_seed=42,
        inversion_type="ddim",
        dtype=dtype,
    )

    watermark = AutoWatermark.load(
        args.algorithm,
        algorithm_config=args.config,
        diffusion_config=diffusion_config,
    )

    result = {
        "model": args.model,
        "config": args.config,
        "categories": {},
    }

    # --- Category 1: COCO real images ---
    print("=== Category 1: COCO real images ===")
    coco_images = download_coco_images(args.coco_cache_dir, args.max_coco)
    coco_flags = []
    coco_scores = []
    for i, (fpath, img) in enumerate(coco_images):
        print(f"  COCO [{i+1}/{len(coco_images)}]: {fpath}")
        det = watermark.detect_watermark_in_media(img, prompt="")
        coco_flags.append(bool(det["is_watermarked"]))
        coco_scores.append(float(det.get("presence_score", det["raw_full_match_rate"])))

    result["categories"]["coco_real"] = {
        "num_images": len(coco_images),
        "false_positive_rate": mean([1.0 if f else 0.0 for f in coco_flags]) if coco_flags else None,
        "score_summary": summarize(coco_scores),
        "detections": coco_flags,
        "scores": coco_scores,
    }

    # --- Category 2: OOD prompts (same model, unwatermarked) ---
    print("\n=== Category 2: OOD prompts (same model, unwatermarked) ===")
    ood_prompts = OOD_PROMPTS[:args.max_ood_prompts]
    ood_flags = []
    ood_scores = []
    for pi, prompt in enumerate(ood_prompts):
        for seed in range(42, 42 + args.num_seeds_per_prompt):
            reseed_watermark(watermark, seed)
            img = watermark.generate_unwatermarked_media(prompt)
            det = watermark.detect_watermark_in_media(img, prompt=prompt)
            ood_flags.append(bool(det["is_watermarked"]))
            ood_scores.append(float(det.get("presence_score", det["raw_full_match_rate"])))
            print(f"  OOD prompt [{pi+1}/{len(ood_prompts)}] seed={seed}: score={ood_scores[-1]:.4f}")

    result["categories"]["ood_prompts_unwatermarked"] = {
        "num_images": len(ood_flags),
        "false_positive_rate": mean([1.0 if f else 0.0 for f in ood_flags]) if ood_flags else None,
        "score_summary": summarize(ood_scores),
        "prompts": ood_prompts,
    }

    # --- Category 3: OOD prompts (same model, watermarked - positive control) ---
    print("\n=== Category 3: OOD prompts (same model, watermarked - positive control) ===")
    ood_wm_flags = []
    ood_wm_scores = []
    for pi, prompt in enumerate(ood_prompts[:10]):  # smaller set
        for seed in range(42, 42 + args.num_seeds_per_prompt):
            reseed_watermark(watermark, seed)
            img = watermark.generate_watermarked_media(prompt)
            det = watermark.detect_watermark_in_media(img, prompt=prompt)
            ood_wm_flags.append(bool(det["is_watermarked"]))
            ood_wm_scores.append(float(det.get("presence_score", det["raw_full_match_rate"])))
            print(f"  OOD wm [{pi+1}/10] seed={seed}: score={ood_wm_scores[-1]:.4f}")

    result["categories"]["ood_prompts_watermarked"] = {
        "num_images": len(ood_wm_flags),
        "detect_rate": mean([1.0 if f else 0.0 for f in ood_wm_flags]) if ood_wm_flags else None,
        "score_summary": summarize(ood_wm_scores),
    }

    Path(args.output).write_text(json.dumps(to_jsonable(result), indent=2, ensure_ascii=False))

    # CSV summary
    with Path(args.csv_output).open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["category", "num_images", "fp_rate_or_detect_rate",
                          "score_mean", "score_std", "score_min", "score_max"])
        for cat_name, cat_data in result["categories"].items():
            rate = cat_data.get("false_positive_rate", cat_data.get("detect_rate"))
            s = cat_data.get("score_summary") or {}
            writer.writerow([
                cat_name, cat_data["num_images"],
                f"{rate:.4f}" if rate is not None else "",
                f"{s.get('mean', 0):.4f}", f"{s.get('std', 0):.4f}",
                f"{s.get('min', 0):.4f}", f"{s.get('max', 0):.4f}",
            ])

    print(f"\nResults written to {args.output} and {args.csv_output}")


if __name__ == "__main__":
    main()
